class AppError extends Error {
  /**
   * @param {string} code - Một giá trị trong ERROR_CODES
   * @param {string} message - Mô tả lỗi cho người đọc
   * @param {object} [details] - Dữ liệu bổ sung (không chứa thông tin nhạy cảm)
   * @param {number} [statusCode] - HTTP status; mặc định tra theo DEFAULT_STATUS_BY_CODE
   */
  constructor(code, message, details, statusCode) {
    super(message);
    this.name = 'AppError';
    this.code = code;
    if (details !== undefined) {
      this.details = details;
    }
    const resolved = Number(statusCode || DEFAULT_STATUS_BY_CODE[code]);
    if (Number.isInteger(resolved) && resolved >= 400) {
      this.statusCode = resolved;
    }
  }
}

/**
 * REV-03: chuyển lỗi thường (có .code trùng ERROR_CODES) thành AppError để
 * errorResponse không biến nó thành 500.
 * @param {Error} err
 * @returns {AppError|null}
 */
function asAppError(err) {
  if (!err || !err.code || !ERROR_CODES[err.code]) return null;
  if (err instanceof AppError) return err;
  const converted = new AppError(err.code, err.message, err.details, err.statusCode);
  if (Array.isArray(err.errors)) converted.errors = err.errors;
  return converted;
}

module.exports = { AppError, ERROR_CODES, DEFAULT_STATUS_BY_CODE, asAppError };
